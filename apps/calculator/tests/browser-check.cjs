const {chromium} = require('C:/Users/arhan/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  fs.mkdirSync('output', {recursive: true});
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  const context = await browser.newContext({viewport: {width: 1280, height: 1000}, permissions: ['clipboard-read', 'clipboard-write']});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8765/');
  await page.waitForFunction(() => document.querySelector('#letter-rows').children.length === 1);
  const visibleNumber = async selector => (await page.locator(selector).innerText()).replace(/[^\d,]/g, '');
  assert.equal(await visibleNumber('#total-min'), '27440');
  assert.equal(await visibleNumber('#total-max'), '31440');
  assert.equal(await page.locator('#count-0').inputValue(), '8');
  assert.equal(await page.locator('#count-0').getAttribute('readonly'), '');
  await page.locator('#text-0').fill(' АПТЕКА\t24\n ');
  assert.equal(await page.locator('#count-0').inputValue(), '8');
  assert.equal(await visibleNumber('#total-min'), '27440');
  await page.screenshot({path: 'output/desktop.png', fullPage: true});
  await page.locator('#cassette').check();
  assert.equal(await visibleNumber('#total-min'), '44240');
  await page.locator('#film').uncheck();
  assert.equal(await visibleNumber('#total-min'), '42800');
  await page.locator('#cassette').uncheck();
  await page.locator('#text-0').fill('ТЕСТ');
  await page.locator('#height-0').fill('14,99');
  assert.equal(await visibleNumber('#total-min'), '10994');
  await page.locator('#height-0').fill('15');
  assert.equal(await visibleNumber('#total-min'), '8000');
  await page.locator('#height').fill('60');
  await page.locator('#height-0').fill('50');
  assert.equal(await visibleNumber('#total-min'), '22000');
  await page.locator('#height-0').fill('50,01');
  assert.equal(await visibleNumber('#total-min'), '32006');
  await page.locator('#text-0').fill(' \t\n\u00a0');
  assert.equal(await page.locator('#count-0').inputValue(), '0');
  assert.equal(await page.locator('#copy').isDisabled(), true);
  assert.equal(await page.locator('#text-0').getAttribute('aria-invalid'), 'true');
  assert.equal(await page.locator('#breakdown').innerText(), '');
  await page.locator('#text-0').fill('МИР');
  await page.locator('#height-0').fill('20');
  await page.locator('#add-group').click();
  await page.locator('#text-1').fill('ДА');
  await page.locator('#height-1').fill('60');
  await page.locator('#width').fill('300');
  await page.locator('#film').check();
  await page.locator('#cassette').check();
  assert.equal(await visibleNumber('#total-min'), '49700');
  assert.equal(await visibleNumber('#total-max'), '53700');
  await page.locator('#copy').click();
  await page.waitForFunction(() => document.querySelector('#copy-status').textContent === 'Расчёт скопирован.');
  const clipboard = await page.evaluate(() => navigator.clipboard.readText());
  assert.ok(clipboard.replace(/\s/g, '').includes('от49700'));
  assert.ok(clipboard.includes('Текст: МИР'));
  assert.ok(clipboard.includes('Текст: ДА'));
  await page.locator('#height').fill('59');
  assert.equal(await page.locator('#height').getAttribute('aria-invalid'), 'true');
  await page.locator('#height').fill('60');
  await page.locator('.remove-group').nth(0).click();
  assert.equal(await page.locator('#letter-rows > .letter-group').count(), 1);
  assert.equal(await page.locator('#count-0').inputValue(), '2');
  assert.equal(await page.locator('#text-0').inputValue(), 'ДА');
  assert.equal(await page.locator('#count-0').getAttribute('aria-describedby'), 'error-0');
  assert.equal(await page.locator('#text-0').getAttribute('aria-describedby'), 'error-0');
  await page.locator('#text-0').fill('й и\u0306 👨‍👩‍👧‍👦\u200b');
  assert.equal(await page.locator('#count-0').inputValue(), '3');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#letter-rows').children.length === 1);
  for (const width of [390, 320]) {
    await page.setViewportSize({width, height: 844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}px`);
    await page.screenshot({path: `output/mobile-${width}.png`, fullPage: true});
  }
  assert.deepEqual(errors, []);
  await browser.close();
  console.log(JSON.stringify({passed: true, viewports: [1280, 390, 320], errors, screenshots: ['output/desktop.png','output/mobile-390.png','output/mobile-320.png']}));
})().catch(error => {console.error(error); process.exit(1);});

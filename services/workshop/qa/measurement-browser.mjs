  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const posted=page.waitForResponse(r=>r.url().endsWith('/api/transactions')&&r.request().method()==='POST');
  await dialog.getByRole('button',{name:'Записать оплату',exact:true}).click();
  const response=await posted; const result=await response.json(); assert.equal(response.status(),201, result.code);
  const transaction=result.transaction; assert.equal(transaction.category,'Замеры'); assert.equal(transaction.amount,123); assert.equal(transaction.orderNumber,null); assert.equal(transaction.counterparty,null);
